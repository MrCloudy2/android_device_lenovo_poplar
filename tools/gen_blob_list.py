#!/usr/bin/env python3
"""Generate proprietary-files.txt for poplar from the stock vendor image.

Rule (same as the clove tree): every stock vendor file goes in, except what
the device tree provides (init, fstab, VINTF base, sepolicy, props) and what
LineageOS builds from source (AOSP libraries and HALs).

Usage: gen_blob_list.py <vendor_x> <clove proprietary-files.txt> <aosp_names.txt> <out> [aidl_versions.txt]

aidl_versions.txt: "<interface> <frozen version|current>" lines from the tree's aidl_api dirs.
A <iface>-V<n>-{ndk,cpp} lib is only treated as built when version n exists in the tree.
"""
import os
import re
import sys

vendor_dir, clove_list, aosp_names_file, out = sys.argv[1:5]
aidl_versions = {}
if len(sys.argv) > 5:
    for l in open(sys.argv[5]):
        i, v = l.split()
        aidl_versions.setdefault(i, set()).add(v)


def aidl_buildable(iface, ver):
    vs = aidl_versions.get(iface)
    if vs is None:
        return True  # no aidl_api info (e.g. unfrozen/vendor-only): trust the name
    frozen = [int(v) for v in vs if v.isdigit()]
    return str(ver) in vs or ("current" in vs and ver == max(frozen, default=0) + 1)

# Paths the device tree or the build provides.
EXCLUDE_RE = [re.compile(p) for p in (
    r"^vendor/lib(64)?/modules$",
    r"^vendor/etc/selinux/",
    r"^vendor/(odm/etc/)?build\.prop$",
    r"^vendor/(etc/)?(ro|rw)\.prop$",
    r"^vendor/odm/etc/(group|passwd)$",
    # Per-SKU radio fragments: ro.boot.product.hardware.sku is never set on
    # this device, so VINTF never loads them (the base manifest has slot1).
    r"^vendor/odm/etc/vintf/",
    r"^vendor/etc/(group|passwd)$",
    r"^vendor/etc/vintf/(manifest|compatibility_matrix)\.xml$",
    r"^vendor/etc/init/hw/",
    r"^vendor/etc/fstab\.",
    r"^vendor/etc/ueventd\.rc$",
    r"^vendor/etc/init\.insmod\..*\.cfg$",
    r"^vendor/bin/init\.insmod\.sh$",
    r"^vendor/overlay/",
    r"^vendor/etc/linker\.config\.pb$",
    # generated by the build (stock fs_config_* are empty: no vendor AIDs)
    r"^vendor/etc/(aconfig_flags\.pb|build_flags\.json|fs_config_(dirs|files))$",
    r"^vendor/etc/aconfig/",
    # installed by AOSP source modules (an exported module owns the path)
    r"^vendor/apex/com\.android\.hardware\.cas\.apex$",
    r"^vendor/etc/aidl/(hfp|le_audio)/",
    r"^vendor/etc/mkshrc$",
    r"^vendor/etc/permissions/features_com\.android\.virt\.xml$",
    r"^vendor/etc/(boringssl_self_test.*|NOTICE.*)",
    r"^vendor/etc/permissions/(android\.hardware|android\.software|handheld_core_hardware)",
    r"^vendor/lib(64)?/(libext2|libclang_rt)",
)]

# HALs and tools LineageOS builds (device.mk), with their init/VINTF files,
# plus stock debug/factory tools we do not ship.
BUILT_BASENAMES = {
    "hostapd", "wpa_supplicant", "wpa_cli", "vndservicemanager", "vndservice",
    "wlan_assistant", "chipinfo", "toybox_vendor", "toolbox", "sh",
    "logwrapper", "vendor_mke2fs", "mke2fs", "dumpsys", "dmabuf_dump", "awk",
    "aee_aedv", "aee_aedv64", "aee_dumpstatev", "aeev", "iperf", "stroke",
    "trusty-ut-ctrl", "sensors.camera.fac.cal", "boringssl_self_test32",
    "boringssl_self_test64",
    "android.hardware.boot-service.mtk",
    "android.hardware.drm-service.clearkey",
    "android.hardware.health-service.example",
    "android.hardware.memtrack-service.mediatek",
    "android.hardware.sensors-service.multihal",
    "android.hardware.wifi-service-lazy",
    "android.hardware.contexthub-service.tinysys",
    # same upstream tools are built from source (external/iw, wpa_supplicant_8)
    "iw", "hostapd_cli",
}
# Libraries the 24.0 tree builds itself (for the vendor partition) although
# clove shipped them as blobs: Soong rejects a prebuilt with the same name.
SOURCE_BUILT = {
    "vendor/lib/vendor.mediatek.hardware.mtkpower-V2-ndk.so",
    "vendor/lib64/vendor.mediatek.hardware.mtkpower-V2-ndk.so",
    # provided by prebuilts/misc/protobuf_vendorcompat
    "vendor/lib/libprotobuf-cpp-full-21.12.so",
    "vendor/lib64/libprotobuf-cpp-full-21.12.so",
    "vendor/lib/libaconfig_storage_read_api_cc.so",
    "vendor/lib64/libaconfig_storage_read_api_cc.so",
    "vendor/lib/vendor.mediatek.hardware.bluetooth.audio@2.1.so",
    "vendor/lib64/vendor.mediatek.hardware.bluetooth.audio@2.1.so",
    "vendor/lib/vendor.mediatek.hardware.bluetooth.audio@2.2.so",
    "vendor/lib64/vendor.mediatek.hardware.bluetooth.audio@2.2.so",
    "vendor/lib/vendor.mediatek.hardware.lbs@1.0.so",
    "vendor/lib64/vendor.mediatek.hardware.lbs@1.0.so",
    "vendor/lib/vendor.mediatek.hardware.netdagent@1.0.so",
    "vendor/lib64/vendor.mediatek.hardware.netdagent@1.0.so",
    "vendor/lib/vendor.mediatek.hardware.mtkpower-V1-ndk.so",
    "vendor/lib64/vendor.mediatek.hardware.mtkpower-V1-ndk.so",
}
# MTK libraries that only share a name with an AOSP module (hardware/ril):
# the stock RIL needs MTK's own versions, never drop them.
KEEP_BASENAMES = {"libril.so", "librilutils.so", "libreference-ril.so"}
# MTK libraries whose name is taken by an unrelated non-Android module in the
# tree (Rust host libformatter, static-only libarmnn): give them a distinct
# Soong module name. extract-files.py maps the dependency with lib_fixups.
ANNOTATE = {
    "libformatter.so": ";MODULE_SUFFIX=_vendor",
    "libarmnn.so": ";MODULE_SUFFIX=_vendor",
    # Same names as hardware/mediatek modules (both namespaces are exported
    # to Make, which rejects duplicate module names); keep the stock libs.
    "libion_mtk.so": ";MODULE_SUFFIX=_vendor",
    "libmtkperf_client_vendor.so": ";MODULE_SUFFIX=_vendor",
    "libperfctl_vendor.so": ";MODULE_SUFFIX=_vendor",
    "libpowerhalwrap_vendor.so": ";MODULE_SUFFIX=_vendor",
}
# Stock files installed under another file name, because a source module in
# an exported namespace always gets an install rule for the original path:
# - the MTK bluetooth.audio AIDL lib (its source build mixes audio.common
#   V1/V3); dependents are patched with replace_needed in extract-files.py
# - the stock MTK thermal HAL (hardware/mediatek has a Pixel-style one that
#   needs a thermal_info_config.json we do not have); its rc is patched
RENAME = {
    "vendor/lib/vendor.mediatek.hardware.bluetooth.audio-V1-ndk.so":
        "vendor/lib/vendor.mediatek.hardware.bluetooth.audio-V1-ndk_vendor.so;FIX_SONAME",
    "vendor/lib64/vendor.mediatek.hardware.bluetooth.audio-V1-ndk.so":
        "vendor/lib64/vendor.mediatek.hardware.bluetooth.audio-V1-ndk_vendor.so;FIX_SONAME",
    # MTK GPS navigation lib. external/libmnl (the unrelated netlink lib) also
    # installs vendor/lib64/libmnl.so, so ship it as libmnl_mtk.so; mnld's
    # NEEDED entry is patched in extract-files.py.
    "vendor/lib64/libmnl.so": "vendor/lib64/libmnl_mtk.so;FIX_SONAME",
    "vendor/bin/hw/android.hardware.thermal-service.mediatek":
        "vendor/bin/hw/android.hardware.thermal-service.mediatek-stock",
}
BUILT_RC_VINTF_RE = re.compile(
    r"^vendor/etc/(init|vintf/manifest)/("
    r"aee_aedv|android\.hardware\.boot-service\.mtk|android\.hardware\.drm-service\.clearkey|"
    r"android\.hardware\.health-service\.example|android\.hardware\.sensors-(service-)?multihal|"
    r"android\.hardware\.wifi-service|android\.hardware\.wifi\.supplicant|android\.hardware\.wifi\.hostapd|"
    r"hostapd|memtrack-mediatek|vndservicemanager|wlan_assistant|boringssl_self_test|chipinfo_init"
    r")")

aosp_names = set()
with open(aosp_names_file) as f:
    aosp_names = {l.strip() for l in f if l.strip()}

# clove entries: keep their annotated form, keyed by source path.
clove = {}
clove_tail = []
with open(clove_list) as f:
    in_tail = False
    for line in f:
        line = line.rstrip("\n")
        if line.startswith("# Unfrozen"):
            in_tail = True
            continue
        if not line or line.startswith("#"):
            continue
        src = re.split(r"[:;|]", line.lstrip("-"), maxsplit=1)[0]
        if in_tail:
            clove_tail.append((src, line))
        else:
            clove[src] = line
tail_srcs = {s for s, _ in clove_tail}

entries = {}
skipped = {"excluded": 0, "built": 0, "aosp_lib": 0, "symlink": 0}
for root, dirs, files in os.walk(vendor_dir):
    for name in dirs + files:
        full = os.path.join(root, name)
        if os.path.isdir(full) and not os.path.islink(full):
            continue
        rel = "vendor/" + os.path.relpath(full, vendor_dir)
        if any(r.search(rel) for r in EXCLUDE_RE):
            skipped["excluded"] += 1
            continue
        base = os.path.basename(rel)
        if base in BUILT_BASENAMES or BUILT_RC_VINTF_RE.search(rel):
            skipped["built"] += 1
            continue
        if os.path.islink(full):
            target = os.readlink(full)
            if target.startswith("mt6768/"):
                # Recreated by ;SYMLINK= on the mt6768/ entry below.
                continue
            skipped["symlink"] += 1
            continue
        if rel in SOURCE_BUILT:
            skipped["built"] += 1
            continue
        if rel in tail_srcs:
            continue
        if rel in clove:
            entries[rel] = clove[rel]
            continue
        if re.match(r"^vendor/lib(64)?/", rel) and base.endswith(".so"):
            stem = base[:-3]
            m = re.match(r"^(.+)-V(\d+)-(ndk|cpp)$", stem)
            iface = m.group(1) if m else stem
            if base in KEEP_BASENAMES:
                pass
            elif m and not aidl_buildable(iface, int(m.group(2))):
                pass  # this version is not in the tree: keep the stock lib
            elif stem in aosp_names or iface in aosp_names:
                skipped["aosp_lib"] += 1
                continue
        line = rel
        m = re.match(r"^(vendor/lib(64)?)/mt6768/(.+\.so)$", rel)
        if m and os.path.islink(os.path.join(vendor_dir, m.group(1)[7:], m.group(3))):
            line += ";SYMLINK=%s/%s" % (m.group(1), m.group(3))
        entries[rel] = line

for rel, line in list(entries.items()):
    if rel in RENAME:
        entries[rel] = line = "%s:%s" % (rel, RENAME[rel])
    ann = ANNOTATE.get(os.path.basename(rel))
    if ann and ann not in line:
        entries[rel] = line + ann

with open(out, "w") as f:
    f.write("""# Proprietary files for Lenovo Tab (TB311XU / poplar).
#
# All blobs are from the stock Lenovo firmware:
#   ro.vendor.build.version.release=15 (vendor), ZUI 17 / Android 16 system
#   ro.build.fingerprint=Lenovo/TB311XU_EEA/TB311XU:16/BP2A.250605.031.A3/37.350.260708W:user/release-keys
#
# The vendor partition is rebuilt from these blobs; init scripts, fstabs, the
# boot control HAL, SELinux policy, VINTF manifest and props come from this
# tree or from the LineageOS build instead. Generated by gen_blob_list.py
# from the clove_row_wifi list plus the TB311XU-only files.
#
""")
    for rel in sorted(entries):
        f.write(entries[rel] + "\n")
    present_tail = [l for s, l in clove_tail if os.path.lexists(os.path.join(vendor_dir, s[7:]))]
    if present_tail:
        f.write("\n# Unfrozen in LineageOS AOSP; stock copies, module-suffixed _vendor\n")
        for l in present_tail:
            f.write(l + "\n")

new = [e for e in entries if e not in clove]
print("entries=%d (from clove=%d, new=%d) tail=%d skipped=%s" % (
    len(entries), len(entries) - len(new), len(new), len(present_tail), skipped))
